"""Builds a sweep plan for elem-run.ps1 from an elem_report.py JSON (the costs of a measurement run).

usage: python -I elem_plan.py <report.json> <out-plan.txt> [--passes N] [--depth D] [--programs N] [--materials N]
                              [--seconds S] [--base-every K] [--min-ms M] [--extra FILE]

Steps: a base step, then one step per element, a base step after every K element steps:
- the N costliest pass groups (labels folded to D marker levels; rule "pass <label>"),
- the engine draw kinds and the costliest l3-other functions (rules "kind <name>" / "va <hex>"),
- the N costliest dispatch programs (rule "prog <hex>"),
- an @topmat line for the N costliest materials of the sweep run itself (guest skip "gmat").
--extra appends the lines of FILE (hand-written steps) before the dispatch programs.
"""
import argparse
import collections
import json
import re


def fold(label, depth):
    queue, _, path = label.partition("|")
    parts = path.split("/") if path else []
    return queue + "|" + "/".join(parts[:depth])


def slug(text, limit=40):
    text = re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-")
    return text[:limit] or "x"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("report")
    ap.add_argument("out")
    ap.add_argument("--passes", type=int, default=14)
    ap.add_argument("--depth", type=int, default=2)
    ap.add_argument("--programs", type=int, default=8)
    ap.add_argument("--materials", type=int, default=8)
    ap.add_argument("--seconds", type=int, default=40)
    ap.add_argument("--base-every", type=int, default=4)
    ap.add_argument("--min-ms", type=float, default=150.0, help="minimum worker+commit ms per 10 s for a pass group")
    ap.add_argument("--extra")
    args = ap.parse_args()
    report = json.load(open(args.report, encoding="utf-8"))
    groups = collections.defaultdict(float)
    for label, row in report["passes"].items():
        groups[fold(label, args.depth)] += row[0] + row[1] + row[2]
    steps = []
    for label, ms in sorted(groups.items(), key=lambda kv: -kv[1])[:args.passes]:
        if ms < args.min_ms:
            break
        # A group without marker levels (the bare queue, "q0|") is skipped by its exact label only.
        steps.append((f"pass-{slug(label)}", f"pass {label}" if not label.endswith("|") else f"passx {label}"))
    for kind in ("item", "instanced", "instanced-b"):
        steps.append((f"kind-{kind}", f"kind {kind}"))
    others = sorted(((k, v) for k, v in report["engines"].items() if k.startswith("other ")), key=lambda kv: -(kv[1][0] + kv[1][1]))[:6]
    for key, _ in others:
        steps.append((f"va-{key.split()[1]}", f"va {key.split()[1]}"))
    if args.extra:
        for line in open(args.extra, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#"):
                parts = line.split(None, 1)
                steps.append((parts[0], parts[1] if len(parts) > 1 else ""))
    progs = sorted(((k, v) for k, v in report["programs"].items() if k.startswith("c ")), key=lambda kv: -(kv[1][0] + kv[1][1]))[:args.programs]
    for key, _ in progs:
        address = key.split()[1]
        steps.append((f"prog-{address}", f"prog {address}"))
    lines = [f"base0 {args.seconds}"]
    for index, (label, control) in enumerate(steps, 1):
        lines.append(f"{label} {args.seconds} {control}")
        if index % args.base_every == 0:
            lines.append(f"base{index} {args.seconds}")
    if args.materials:
        lines.append(f"@topmat {args.materials} {args.seconds} gmat {args.base_every}")
    lines.append(f"baseZ {args.seconds}")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# generated by elem_plan.py from " + args.report + "\n" + "\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"{len(lines)} lines, about {len(lines) * args.seconds / 60:.0f} min")


if __name__ == "__main__":
    main()
